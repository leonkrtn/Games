const toPath = (list) =>
  list
    .map(
      (poly) =>
        `M${poly
          .split(',')
          .map((pt) => {
            const [lon, lat] = pt.trim().split(' ').map(Number);
            return project(lon, lat).map((v) => v.toFixed(1)).join(' ');
          })
          .join(' L')} Z`,
    )
    .join(' ');

/** Die Weltkarte ohne Stecknadeln (Meer, Gradnetz, Land, Binnenmeere). */
export function worldMap() {
  const grid = [
    ...[-150, -120, -90, -60, -30, 0, 30, 60, 90, 120, 150].map((lon) => `M${project(lon, 78)[0]} 0 V${MAP_H}`),
    ...[60, 30, 0, -30].map((lat) => `M0 ${project(0, lat)[1]} H${MAP_W}`),
  ].join(' ');
  return `<rect width="${MAP_W}" height="${MAP_H}" fill="#e6f0f4"/>
<path d="${grid}" fill="none" stroke="#c9dde6" stroke-width="1" stroke-dasharray="3 4"/>
<path d="${toPath(LAND)}" fill="#f7f1e2" stroke="${INK}" stroke-width="1.2" stroke-linejoin="round"/>
<path d="${toPath(LAKES)}" fill="#e6f0f4" stroke="${INK}" stroke-width="1" stroke-linejoin="round"/>`;
}

const INK = '#141414';
const sh = (d, fill, w = 1.6) => `<path d="${d}" fill="${fill}" stroke="${INK}" stroke-width="${w}" stroke-linejoin="round"/>`;
const ln = (d, color, w = 1) =>
  `<path d="${d}" fill="none" stroke="${color}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
const sky = (fill) => `<rect width="360" height="260" fill="${fill}"/>`;
const cloud = (x, y, s = 1) =>
  `<path transform="translate(${x} ${y}) scale(${s})" d="M0 0 C-1 -6 5 -9 9 -6 C11 -13 22 -13 24 -6 C29 -8 34 -4 32 1 C33 3 31 5 29 5 L2 5 C-1 5 -2 2 0 0 Z" fill="#fff" stroke="${INK}" stroke-width="${(1.4 / s).toFixed(2)}" stroke-linejoin="round"/>`;
const ground = (y, fill, bump = 10) => sh(`M-2 ${y} Q180 ${y - bump} 362 ${y} V262 H-2 Z`, fill);
const heartD = 'M0 3.2 C-1.6 0.4 -5.6 0.6 -5.6 -2.6 C-5.6 -5 -2.6 -6.2 0 -3.4 C2.6 -6.2 5.6 -5 5.6 -2.6 C5.6 0.6 1.6 0.4 0 3.2 Z';
const heart = (x, y, s, r, fill) => `<path transform="translate(${x} ${y}) rotate(${r}) scale(${s})" d="${heartD}" fill="${fill}"/>`;
const range = (n) => Array.from({ length: n }, (_, i) => i);
const tree = (x, y, r, fill = '#8fb36b') =>
  `${sh(`M${x - 2.5} ${y} V${y - r} H${x + 2.5} V${y} Z`, '#7a5a3c', 1.3)}<circle cx="${x}" cy="${y - r - r * 0.55}" r="${r}" fill="${fill}" stroke="${INK}" stroke-width="1.5"/>${ln(`M${x - r * 0.6} ${y - r * 1.75} A${r * 0.7} ${r * 0.7} 0 0 1 ${x - r * 0.05} ${y - r * 2.25}`, '#b5cf92', 1.4)}`;
const palm = (x, y, h, lean = -1) => {
  const tx = x + lean * h * 0.3;
  const ty = y - h;
  const L = h * 0.5;
  const leaves = [-172, -140, -105, -75, -40, -8]
    .map((a) => {
      const r = (a * Math.PI) / 180;
      const ex = tx + Math.cos(r) * L;
      const ey = ty + Math.sin(r) * L * 0.35 + Math.abs(Math.cos(r)) * L * 0.45;
      const cx = tx + Math.cos(r) * L * 0.55;
      const cy = ty + Math.sin(r) * L * 0.55 - L * 0.12;
      const nx = -Math.sin(r) * L * 0.12;
      const ny = Math.cos(r) * L * 0.12;
      return sh(`M${tx} ${ty} Q${(cx + nx).toFixed(1)} ${(cy + ny).toFixed(1)} ${ex.toFixed(1)} ${ey.toFixed(1)} Q${(cx - nx).toFixed(1)} ${(cy - ny + 4).toFixed(1)} ${tx} ${ty} Z`, '#4f8a4a', 1.3);
    })
    .join('');
  const trunk = `M${x - 3.5} ${y} Q${x + lean * h * 0.02} ${y - h * 0.6} ${tx - 2} ${ty} L${tx + 2} ${ty} Q${x + lean * h * 0.02 + 7} ${y - h * 0.6} ${x + 3.5} ${y} Z`;
  return `${sh(trunk, '#9a7653', 1.4)}${range(Math.floor(h / 12))
    .map((i) => {
      const t = (i + 1) / (Math.floor(h / 12) + 1);
      const px = x + (tx - x) * t * t + lean * h * 0.04 * Math.sin(t * 3);
      return ln(`M${(px - 3).toFixed(1)} ${(y - h * t).toFixed(1)} l6 -2`, '#6f5338', 1);
    })
    .join('')}<circle cx="${tx - 2.5}" cy="${ty + 3}" r="2.8" fill="#6b4a2b" stroke="${INK}" stroke-width="1"/><circle cx="${tx + 3}" cy="${ty + 4}" r="2.8" fill="#6b4a2b" stroke="${INK}" stroke-width="1"/>${leaves}`;
};

